	create database imovelnet;
	use imovelnet;




	create table ESTADO(
	SGESTADO CHAR(2) PRIMARY KEY,
	NMESTADO VARCHAR(20)
	);

	create table VENDEDOR(
	CDVENDEDOR int primary key,
	NMVENDEDOR varchar(40),
	NMENDERECO varchar(40),
	NRCPF decimal(11),
	NMCIDADE varchar(20),
	NMBAIRRO varchar(20),
	SGESTADO CHAR(2),
	TELEFONE VARCHAR(20),
	EMAIL VARCHAR(80)
	);
	create table CIDADE(
	CDCIDADE INT,
	SGESTADO CHAR(2),
	NMCIDADE VARCHAR(20),

	PRIMARY KEY (CDCIDADE, SGESTADO),
	FOREIGN KEY (SGESTADO) REFERENCES ESTADO(SGESTADO)
	);

	create table BAIRRO(
	CDBAIRRO INT,
	CDCIDADE INT,
	SGESTADO CHAR(2),
	NMBAIRRO VARCHAR(20),

	PRIMARY KEY (CDBAIRRO,CDCIDADE,SGESTADO),
	FOREIGN KEY (CDCIDADE,SGESTADO) REFERENCES CIDADE(CDCIDADE,SGESTADO)
	);

	create table IMOVEL(
	CDIMOVEL int primary key,
	CDVENDEDOR int,
	CDBAIRRO int,
	CDCIDADE INT,
	SGESTADO CHAR(2),
	NMENDERECO VARCHAR(40),
	NRAREAUTIL DECIMAL(10,2),
	NRAREATOTAL DECIMAL(10,2),
	DSIMOVEL VARCHAR(300),
	VLPRECO DECIMAL(16,2),
	NROFERTAS int,
	STVENDIDO CHAR(1),
	DTLANCTO DATE,
	IMOVEL_INDICADO INT,
	FOREIGN KEY (CDVENDEDOR) REFERENCES VENDEDOR(CDVENDEDOR),
	FOREIGN KEY (CDBAIRRO, CDCIDADE, SGESTADO) REFERENCES BAIRRO(CDBAIRRO,CDCIDADE,SGESTADO),
	FOREIGN KEY (IMOVEL_INDICADO) REFERENCES IMOVEL(CDIMOVEL)
	);

	create table FAIXA_IMOVEL(
	CDFAIXA INT PRIMARY KEY,
	NMFAIXA VARCHAR(30),
	VLMINIMO DECIMAL(14,2),
	VLMAXIMO DECIMAL(14,2)

	);
		
	create table COMPRADOR(
	CDCOMPRADOR INT PRIMARY KEY,
	NMCOMPRADOR VARCHAR(40),
	NMENDERECO VARCHAR(40),
	NRCPF DECIMAL(11),
	NMCIDADE VARCHAR(20),
	NMBAIRRO VARCHAR(20),
	SGESTADO CHAR(2),
	TELEFONE VARCHAR(20),
	EMAIL VARCHAR(80)

	);

	create table OFERTA(
	CDIMOVEL INT,
	CDCOMPRADOR INT,
	VLOFERTA DECIMAL(16,2),
	DTOFERTA DATE,

	PRIMARY KEY (CDIMOVEL, CDCOMPRADOR),
	FOREIGN KEY (CDIMOVEL) REFERENCES IMOVEL(CDIMOVEL),
	FOREIGN KEY (CDCOMPRADOR) REFERENCES COMPRADOR(CDCOMPRADOR)
	);